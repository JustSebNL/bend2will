//go:build !windows && !linux && !darwin

package bend2will

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// fallbackPlatform covers the operating systems bend2will has no native service
// integration for: FreeBSD, the BSDs, Solaris, and anything else that compiles.
//
// Supervision, restart and logging all work. Status reporting is a no-op, and
// install writes a plain shell wrapper under a caller-chosen directory, which is
// enough to be driven by whatever init system the host actually has.
type fallbackPlatform struct {
	goos string
}

func newFallbackPlatform(goos string) Platform { return &fallbackPlatform{goos: goos} }

func (p *fallbackPlatform) Name() string { return p.goos }

func (p *fallbackPlatform) Connect(ctx context.Context, cfg *Config, mode Mode, sup SuperviseFunc, stopper *Stopper) (bool, error) {
	if mode == ModeService {
		return false, fmt.Errorf("bend2will: %s has no service manager integration; "+
			"run with mode=console under a supervisor such as runit, s6 or daemontools", p.goos)
	}
	return false, nil
}

func (p *fallbackPlatform) ReportStatus(Status) error { return nil }

func (p *fallbackPlatform) Definition(cfg *Config) (Definition, error) {
	if err := cfg.Validate(); err != nil {
		return Definition{}, err
	}
	dir := "/etc/" + cfg.Name
	return Definition{
		Kind:     "script",
		Path:     dir + "/run",
		Contents: shellWrapper(cfg),
		Instructions: []string{
			fmt.Sprintf("chmod +x %s", dir+"/run"),
			"arrange for your init system to run this script and to send SIGTERM for stop",
		},
	}, nil
}

func (p *fallbackPlatform) Install(ctx context.Context, cfg *Config, opts InstallOptions) error {
	if err := opts.Validate(p.Name()); err != nil {
		return err
	}
	def, err := p.Definition(cfg)
	if err != nil {
		return err
	}
	if opts.DryRun {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(def.Path), 0o755); err != nil {
		return fmt.Errorf("bend2will: create %s: %w", filepath.Dir(def.Path), err)
	}
	if err := os.WriteFile(def.Path, []byte(def.Contents), 0o755); err != nil {
		return fmt.Errorf("bend2will: write %s: %w", def.Path, err)
	}
	return nil
}

func (p *fallbackPlatform) Uninstall(ctx context.Context, name string, purge bool) error {
	path := "/etc/" + name + "/run"
	if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("bend2will: remove %s: %w", path, err)
	}
	if purge {
		_ = os.Remove("/etc/" + name)
	}
	return nil
}

func (p *fallbackPlatform) Start(ctx context.Context, name string) error {
	return fmt.Errorf("bend2will: %s has no service manager; start the script under your init system", p.goos)
}

func (p *fallbackPlatform) Stop(ctx context.Context, name string) error {
	return fmt.Errorf("bend2will: %s has no service manager; stop the script under your init system", p.goos)
}

func (p *fallbackPlatform) Status(ctx context.Context, name string) (ServiceStatus, error) {
	return ServiceStatus{Name: name, State: StatusUnknown, Detail: "no service manager on " + p.goos}, nil
}

func (p *fallbackPlatform) Close() error { return nil }

// shellWrapper renders a POSIX sh wrapper that execs the supervised program
// under the exported environment.
func shellWrapper(cfg *Config) string {
	var b strings.Builder
	fmt.Fprintf(&b, "#!/bin/sh\n# generated by bend2will for %s\nset -eu\n\n", cfg.Name)
	if cfg.Dir != "" {
		fmt.Fprintf(&b, "cd %s\n", shellQuote(cfg.Dir))
	}
	for _, kv := range cfg.Env {
		fmt.Fprintf(&b, "export %s\n", kv)
	}
	fmt.Fprintf(&b, "exec %s\n", cfg.CommandLine())
	return b.String()
}

func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }
