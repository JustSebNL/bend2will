//go:build windows

package bend2will

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// portableIsUserService reports whether this platform has a per-user service
// manager.
//
// It does not. The Service Control Manager is machine-wide and registering a
// service with it needs administrator rights, so a portable install on Windows
// cannot be a service and uses a logon launcher instead.
func portableIsUserService() bool { return false }

// launcherName is the script a portable install uses on Windows.
func launcherName(cfg *Config) string { return cfg.Name + ".cmd" }

// startupFolder returns the per-user Startup folder, where a copy of the launcher
// makes bend2will start at logon without administrator rights.
func startupFolder() string {
	base := os.Getenv("APPDATA")
	if base == "" {
		if home, err := os.UserHomeDir(); err == nil {
			base = filepath.Join(home, "AppData", "Roaming")
		}
	}
	return filepath.Join(base, "Microsoft", "Windows", "Start Menu", "Programs", "Startup")
}

// launcherScript renders a .cmd that starts the supervisor.
//
// The exit code is passed through so that a caller can still tell success from
// failure, and stdout and stderr are left attached so that anything the child
// writes reaches the logon session rather than vanishing.
func launcherScript(cfg *Config, self string) string {
	var b strings.Builder

	fmt.Fprintf(&b, "@echo off\r\n")
	fmt.Fprintf(&b, "rem generated by %s for %q\r\n", CommandName, cfg.Name)
	fmt.Fprintf(&b, "rem This is a portable install: it runs at logon and needs no administrator\r\n")
	fmt.Fprintf(&b, "rem rights. It is not a Windows service, because the Service Control\r\n")
	fmt.Fprintf(&b, "rem Manager is machine-wide. Use 'obey install' for a real service.\r\n")
	fmt.Fprintf(&b, "setlocal\r\n")

	if cfg.Dir != "" {
		fmt.Fprintf(&b, "cd /d %s\r\n", cfg.Dir)
	}
	for _, kv := range cfg.Env {
		k, v, _ := strings.Cut(kv, "=")
		fmt.Fprintf(&b, "set %s=%s\r\n", k, v)
	}
	if cfg.LogPath != "" && cfg.LogPath != "-" && cfg.LogPath != "@" {
		fmt.Fprintf(&b, "%s\r\n", strings.ReplaceAll(cfg.LogPath, "/", `\`))
	}

	argv := []string{
		quoteArg(self),
		"run",
		"--name", cfg.Name,
		"--command", cfg.Command,
	}
	if len(cfg.Args) > 0 {
		argv = append(argv, "--arguments", strings.Join(cfg.Args, argSeparator))
	}
	// ModeConsole, not ModeService: a login launcher is not started by the
	// Service Control Manager, so asking for service mode would make it wait for
	// a dispatcher that will never come.
	argv = append(argv, flattenConfigFlags(cfg, ModeConsole)...)

	fmt.Fprintf(&b, "\r\n%s\r\n", strings.Join(argv, " "))
	fmt.Fprintf(&b, "exit /b %%ERRORLEVEL%%\r\n")
	return b.String()
}
